// Writes src/frame/lucide-icons.ts with the lucide icons that the panel uses.
// Orca draws its icons with the lucide icon set (https://lucide.dev, ISC license). Orca gives an
// HTML panel no icons, so the plugin has a copy of the shapes that it needs.
// Run: node scripts/update-icons.mjs
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NAMES = [
  // panel controls
  'search', 'x', 'plus', 'eye', 'refresh-cw', 'chevron-right', 'folder', 'file',
  // scopes
  'cpu', 'list-checks', 'braces', 'play', 'git-fork', 'network', 'combine', 'shapes', 'unplug', 'package',
  // variables
  'brackets', 'git-commit-horizontal', 'variable', 'sliders-vertical', 'activity', 'binary', 'type', 'plug', 'watch', 'list-ordered',
];

const icons = {};
for (const name of NAMES) {
  const response = await fetch(`https://raw.githubusercontent.com/lucide-icons/lucide/main/icons/${name}.svg`);
  if (!response.ok) { throw new Error(`cannot get the icon "${name}": ${response.status}`); }
  const svg = await response.text();
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
  if (!inner.startsWith('<')) { throw new Error(`unexpected content for "${name}"`); }
  icons[name] = inner;
}

const lines = [
  '// Generated by scripts/update-icons.mjs. Do not edit.',
  '// Icon shapes of the lucide icon set (https://lucide.dev), ISC license, Copyright (c) Lucide Contributors.',
  '// Some icons come from Feather (MIT license, Copyright (c) Cole Bemis).',
  '// Each value is the content of an <svg viewBox="0 0 24 24"> element.',
  'export const LUCIDE: Record<string, string> = {',
  ...Object.entries(icons).map(([name, inner]) => `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`),
  '};',
  '',
];
fs.writeFileSync(path.join(root, 'src', 'frame', 'lucide-icons.ts'), lines.join('\n'));
console.log(`wrote ${Object.keys(icons).length} icons`);
